%
%   Reglas
%
%   CORRESPONDENCIAS ENTRE LINEAS
%
correspondencia(E,L1,L2)   :- linea(L1,E,_), 
                              linea(L2,E,_), 
                              L1 \= L2.
%
%   DIRECCIONES
%
direccion(L1,E1,E2,N,D)    :- linea(L1,E1,N1), 
                              linea(L1,E2,N2), 
                              N2 > N1,
                              N is N2 - N1,
                              terminales(L1,_,D).
direccion(L1,E1,E2,N,D)    :- linea(L1,E1,N1), 
                              linea(L1,E2,N2), 
                              N1 > N2,
                              N is N1 - N2,
                              terminales(L1,D,_).
%
%   RUTAS
%
%
%   MISMA LINEA ENTRE ORIGEN-DESTINO
%
% =================================================================
% REGISTRO GLOBAL TEMPORAL (Dinámico)
% Necesario para acumular los textos antes de forzar el backtracking
% =================================================================
:- dynamic ruta_encontrada/1.

% =================================================================
% REGLA PRINCIPAL QUE LLAMARÁ PYTHON
% =================================================================
buscar_todas_las_rutas(DESDE, HASTA, TextoAlternativa) :-
    % 1. Limpiamos cualquier residuo en la memoria intermedia
    retractall(ruta_encontrada(_)),
    
    % 2. Forzamos a Prolog a explorar cada regla de transbordo
    %    Al final de 'generar_ruta', el motor acumulará los textos en memoria
    (generar_ruta(DESDE, HASTA) ; true),
    
    % 3. Sacamos los textos guardados uno por uno (Backtracking real para Python)
    ruta_encontrada(TextoAlternativa).

% =================================================================
% REGLAS INTERNAS (Tus algoritmos originales modificados con 'fail')
% =================================================================

% Opción A: Misma Línea
generar_ruta(DESDE, HASTA) :- 
    direccion(LINEA, DESDE, HASTA, ESTACIONES, DIRECCION),
    with_output_to(string(Texto), (
        write(' Por la linea '), write(LINEA),
        write(' partir de la estacion '), write(DESDE),
        write(' hacia '), write(DIRECCION),
        write(', en '), write(ESTACIONES), write(' estaciones '),
        write('llega a la estacion '), write(HASTA),
        write(' de la linea '), write(LINEA), write('. \n ')
    )),
    assertz(ruta_encontrada(Texto)),
    fail. % <--- Fuerza a Prolog a saltar a la siguiente regla

% Opción B: Con 1 Correspondencia
generar_ruta(DESDE, HASTA) :- 
    linea(L1, DESDE, _), linea(L2, HASTA, _), L1 \= L2, DESDE \= HASTA,
    correspondencia(C, L1, L2), DESDE \= C, C \= HASTA,
    direccion(L1, DESDE, C, EST1, DIR1),
    direccion(L2, C, HASTA, EST2, DIR2),
    TOTAL is EST1 + EST2, 
    with_output_to(string(Texto), (
        write(' Por la linea '), write(L1),
        write(' partir de la estacion '), write(DESDE),
        write(' hacia '), write(DIR1),
        write(', en '), write(EST1), write(' estaciones '),
        write('llega a la correspondencia '), write(C),
        write(' para tomar la linea '), write(L2), 
        write(' hacia '), write(DIR2), 
        write(', en '), write(EST2), write(' estaciones '),
        write('llega a la estacion '), write(HASTA),
        write(', TOTAL ESTACIONES '), write(TOTAL), write('. \n ')
    )),
    assertz(ruta_encontrada(Texto)),
    fail. % <--- Fuerza a Prolog a saltar a la siguiente regla

